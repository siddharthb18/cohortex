function canonical(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`;
  if (value && typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>).sort(([a], [b]) =>
      a.localeCompare(b),
    );
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonical(v)}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

const steps: Step[] = [];
const evidence: Record<string, EvidenceRecord> = {};
let clock = START;
const iso = (t: number) => new Date(t).toISOString().replace('.000Z', 'Z');

function addStep<K extends Step['kind']>(
  kind: K,
  node: string,
  payload: Extract<Step, { kind: K }>['payload'],
  ms: number,
) {
  const started = clock;
  clock += ms;
  const step = {
    seq: steps.length + 1,
    node,
    kind,
    payload,
    started_at: iso(started),
    ended_at: iso(clock),
  } as Step;
  steps.push(step);
  clock += 120;
  return step;
}

const SOURCES: Record<string, string> = {
  'fleet.cohort_afr': 'fleet-api /v1/cohorts/{source}/{model}/afr',
  'fleet.compare_cohorts': 'fleet-api /v1/cohorts/compare',
  'fleet.fleet_summary': 'fleet-api /v1/fleet/summary',
  'fleet.smart_trend': 'fleet-api /v1/cohorts/{source}/{model}/smart-trend',
  'fleet.failed_drives': 'fleet-api /v1/cohorts/{source}/{model}/failed-drives',
  'stats.compare_rates': 'mcp-stats (pure function)',
};

function toolCall(
  tool: string,
  args: Record<string, unknown>,
  data: unknown,
  summary: string,
  ms: number,
  ok = true,
) {
  const seq = steps.length + 1;
  const evidence_id = `ev_${createHash('sha256')
    .update(`${INVESTIGATION_ID}|${seq}|${tool}|${canonical(args)}`)
    .digest('hex')
    .slice(0, 16)}`;
  const created = iso(clock + ms);
  evidence[evidence_id] = {
    evidence_id,
    tool,
    args,
    created_at: created,
    result: {
      evidence_id,
      tool,
      args,
      source: SOURCES[tool] ?? tool,
      generated_at: created,
      data,
      truncated: false,
      next_page: null,
    },
  };
  addStep('tool_call', 'agent', { tool, args, evidence_id, ok, summary }, ms);
  return evidence_id;
}

