function alertFor(name: string, opened: string): SuggestedAlert {
  const m = backblaze.find((x) => x.model === name);
  if (!m) throw new Error(name);
  const [base, cur] = model.afrSeries(m, '2026-01-01', '2026-06-30', 'quarter');
  if (!base || !cur) throw new Error('quarters');
  const r = compareRates(cur.failures, cur.drive_days, base.failures, base.drive_days);
  return {
    alert_id: createHash('sha256')
      .update(`alert|${name}`)
      .digest('hex')
      .slice(0, 32)
      .replace(/(.{8})(.{4})(.{4})(.{4})(.{12})/, '$1-$2-$3-$4-$5'),
    source: 'backblaze',
    model: name,
    window_start: '2026-04-01',
    window_end: '2026-06-30',
    baseline_afr: Number(base.afr_pct.toFixed(4)),
    current_afr: Number(cur.afr_pct.toFixed(4)),
    rate_ratio: Number(r.rate_ratio.toFixed(4)),
    p_value: Number(r.p_value.toPrecision(4)),
    status: 'open',
    opened_at: opened,
    suggested_question:
      name === HERO
        ? QUESTION
        : `Why did the failure rate of ${name} rise in Q2 2026, and is the increase real?`,
  };
}
