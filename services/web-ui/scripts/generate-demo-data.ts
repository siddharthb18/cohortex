interface Spec {
  model: string;
  drives: number;
  capacity: number | null;
  /** AFR % per quarter (one entry per quarter in the source window). */
  afr: number[];
  age: number;
  growth?: number;
}

function monthsBetween(firstYear: number, count: number): string[] {
  return Array.from({ length: count }, (_, i) => {
    const y = firstYear + Math.floor(i / 12);
    const m = (i % 12) + 1;
    return `${y}-${String(m).padStart(2, '0')}`;
  });
}

function days(period: string): number {
  const [y, m] = period.split('-').map(Number);
  return new Date(Date.UTC(y ?? 2000, m ?? 1, 0)).getUTCDate();
}

function poisson(lambda: number, r: () => number): number {
  if (lambda > 30) {
    // Normal approximation (Box-Muller) is plenty for synthetic data.
    const u = Math.max(1e-12, r());
    const v = r();
    const z = Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
    return Math.max(0, Math.round(lambda + z * Math.sqrt(lambda)));
  }
  const limit = Math.exp(-lambda);
  let k = 0;
  let p = 1;
  do {
    k += 1;
    p *= r();
  } while (p > limit);
  return k - 1;
}

function buildModel(
  spec: Spec,
  media: 'hdd' | 'ssd',
  periods: string[],
  monthShape?: (p: string) => number,
): model.DemoModel {
  const r = model.rng(`fleet|${spec.model}`);
  let drives = spec.drives;
  const months = periods.map((period, i) => {
    const quarterIndex = Math.floor(i / 3);
    const afr = spec.afr[quarterIndex] ?? spec.afr[spec.afr.length - 1] ?? 1;
    drives = Math.round(drives * (1 + (spec.growth ?? 0)) * (0.997 + r() * 0.006));
    const drive_days = drives * days(period) - Math.floor(r() * drives * 0.4);
    const shape = monthShape ? monthShape(period) : 1;
    const failures = poisson(((afr * shape) / 36500) * drive_days, r);
    return { period, drive_days, failures, drives };
  });
  return {
    model: spec.model,
    media,
    capacity_bytes: spec.capacity,
    months,
    base_age_days: spec.age,
  };
}

