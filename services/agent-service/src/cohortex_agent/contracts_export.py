"""Export generated contracts: `contracts/report/report.schema.json` from `Report` and
`contracts/openapi/agent-service.yaml` from the FastAPI app (JSON, which is valid YAML 1.2).

    uv run python -m cohortex_agent.contracts_export          # write both files
    uv run python -m cohortex_agent.contracts_export --check  # exit 1 if either is stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from cohortex_agent.schemas import Report

REPO_ROOT = Path(__file__).resolve().parents[4]
REPORT_SCHEMA_PATH = REPO_ROOT / "contracts" / "report" / "report.schema.json"
OPENAPI_PATH = REPO_ROOT / "contracts" / "openapi" / "agent-service.yaml"


def _dump(value: Any) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def report_schema_text() -> str:
    schema = Report.model_json_schema()
    schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", **schema}
    return _dump(schema)


def openapi_text() -> str:
    from cohortex_agent.app import create_app
    from cohortex_agent.config import Settings

    app = create_app(Settings(database_url="postgresql://unused"))
    header = "# Generated by `python -m cohortex_agent.contracts_export`; do not edit.\n"
    return header + _dump(app.openapi())


def outputs() -> dict[Path, str]:
    return {REPORT_SCHEMA_PATH: report_schema_text(), OPENAPI_PATH: openapi_text()}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if check:
            stale.append(str(path.relative_to(REPO_ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO_ROOT)}")
    if stale:
        print("stale generated contracts: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
